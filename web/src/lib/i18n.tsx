interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
  translateError: (message: string, fallback: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  language: "en",
  setLanguage: () => undefined,
  t: (text) => text,
  translateError: (message, fallback) => message || fallback,
});

let activeLanguage: Language | null = null;
const languageListeners = new Set<() => void>();
const pageMetadata: Record<string, readonly [string, string]> = {
  "/": ["Your music library", "Listen to and organize your personal music library with Vervfy."],
  "/login": ["Log in", "Log in to your Vervfy account to access your music library."],
  "/register": ["Create an account", "Create a Vervfy account to organize and listen to your music library."],
  "/credits": ["Credits and data sources", "Attribution, licenses, and data sources used by Vervfy."],
  "/privacy": ["Privacy Policy", "How Vervfy handles account, library, and device information."],
  "/terms": ["Terms and Conditions", "Terms for using the Vervfy music library service."],
};

function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

function currentLanguage(fallback: Language): Language {
  if (activeLanguage) return activeLanguage;
  if (typeof window === "undefined") return fallback;

  try {
    const saved = languageFromLocale(window.localStorage.getItem("vervfy:language"));
    if (saved) return saved;
  } catch (error) {
    console.warn("Could not read the saved language preference.", error);
  }
  return fallback;
}

function updateLanguage(language: Language): void {
  if (activeLanguage === language) return;
  activeLanguage = language;
  for (const listener of languageListeners) listener();
}

export function LanguageProvider({
  children,
  initialLanguage,
}: {
  children: ReactNode;
  initialLanguage: Language;
}) {
  const pathname = usePathname();
  const getLanguage = useCallback(
    () => currentLanguage(initialLanguage),
    [initialLanguage],
  );
  const getServerLanguage = useCallback(() => initialLanguage, [initialLanguage]);
  const language = useSyncExternalStore(
    subscribeLanguage,
    getLanguage,
    getServerLanguage,
  );

  const setLanguage = useCallback((next: Language) => {
    try {
      window.localStorage.setItem("vervfy:language", next);
    } catch (error) {
      console.warn("Could not save the language preference in this browser.", error);
    }
    document.cookie = `vervfy-language=${next}; Path=/; Max-Age=31536000; SameSite=Lax${window.location.protocol === "https:" ? "; Secure" : ""}`;
    document.documentElement.lang = next;
    updateLanguage(next);
  }, []);

  const t = useCallback(
    (text: string) => {
      if (language === "pt-BR") return translations[text] ?? text;
      if (language === "fr") return frenchSpanishTranslations[text]?.[0] ?? text;
      if (language === "es") return frenchSpanishTranslations[text]?.[1] ?? text;
      return text;
    },
    [language],
  );
  const translateError = useCallback(
    (message: string, fallback: string) => {
      const hasTranslation = Boolean(message) && (
        language === "pt-BR"
          ? Object.hasOwn(translations, message)
          : language === "fr" || language === "es"
            ? Object.hasOwn(frenchSpanishTranslations, message)
            : true
      );
      return hasTranslation ? t(message) : t(fallback);
    },
    [language, t],
  );

  useEffect(() => {
    document.documentElement.lang = language;
    const [title, description] =
      pageMetadata[pathname] ?? ["Page not found", "The requested Vervfy page could not be found."];
    document.title = `${t(title)} | Vervfy`;
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute("content", t(description));
  }, [language, pathname, t]);

  const value = useMemo<LanguageContextValue>(
    () => ({ language, setLanguage, t, translateError }),
    [language, setLanguage, t, translateError],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}

export function LanguageSelect({ className = "" }: { className?: string }) {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className={`language-select ${className}`.trim()}>
      <span>{t("Language")}</span>
      <select
        aria-label={t("Language")}
        value={language}
        onChange={(event) => {
          const nextLanguage = event.currentTarget.value;
          setLanguage(languageFromLocale(nextLanguage) ?? "en");
        }}
      >
        <option value="en">English</option>
        <option value="pt-BR">Português (Brasil)</option>
        <option value="fr">Français</option>
        <option value="es">Español</option>
      </select>
    </label>
  );
}

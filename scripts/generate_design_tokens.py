"""Generate browser and inline-consumer tokens from the shared brand palette."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALIASES = {
    "background": "bg",
    "surface": "bg-2",
    "deep": "ink",
    "endpoint": "accent-end",
    "secondary": "text-mid",
    "muted": "text-dim",
    "surfaceRaised": "surface-raised",
    "controlSurface": "surface-input",
    "surfaceHover": "surface-hover",
    "inputBorder": "input-border",
}


def generate():
    palette = json.loads((ROOT / "design-tokens.json").read_text())
    rgb = {
        key: ",".join(str(int(value[i : i + 2], 16)) for i in (1, 3, 5))
        for key, value in palette.items()
    }
    css = "/* Generated by scripts/generate_design_tokens.py. Edit design-tokens.json. */\n:root {\n  color-scheme: dark;\n"
    css += "".join(
        f"  --{ALIASES.get(key, key)}:{value};\n" for key, value in palette.items()
    )
    # Keep the normal logo accent; darken only hover feedback.
    css += (
        "  --action-accent:var(--accent);\n"
        "  --action-end:var(--accent-end);\n"
        "  --action-gradient:linear-gradient(125deg,var(--action-accent),var(--action-end));\n"
        "  --action-hover-brightness:.75;\n"
    )
    for name, key in {
        "bg": "background",
        "surface": "surface",
        "deep": "deep",
        "accent": "accent",
        "border": "highlight",
        "control": "controlSurface",
        "hover": "surfaceHover",
        "light": "highlight",
        "danger": "danger",
    }.items():
        css += f"  --{name}-rgb:{rgb[key]};\n"
    css += (
        "  --surface:var(--bg-2);\n"
        "  --surface-control:rgba(var(--light-rgb),.10);\n"
        "  --surface-control-hover:rgba(var(--light-rgb),.14);\n"
        "  --border:rgba(var(--border-rgb),.10);\n"
        "  --border-hi:rgba(var(--light-rgb),.18);\n"
        "  --line:var(--border);\n"
        "  --muted:var(--text-mid);\n"
    )
    (ROOT / "web/src/app/design-tokens.css").write_text(css + "}\n")
    (ROOT / "web/public/design-tokens.css").write_text(css + "}\n")
    (ROOT / "web/src/lib/design-tokens.ts").write_text(
        "// Generated by scripts/generate_design_tokens.py.\nexport const palette = "
        + json.dumps(palette, indent=2)
        + " as const;\nexport const paletteRgb = "
        + json.dumps(rgb, indent=2)
        + " as const;\n"
    )

    offline = ROOT / "web/public/offline.html"
    offline.write_text(
        re.sub(
            r'(<meta name="theme-color" content=")[^"]+',
            lambda match: match[1] + palette["background"],
            offline.read_text(),
        )
    )

    # Keep the native shell's initial background and setup UI in sync as well.
    app = ROOT / "apple/Vervfy/VervfyApp.swift"
    source = app.read_text().split("// BEGIN GENERATED PALETTE")[0].rstrip()
    swift = "\n\n// BEGIN GENERATED PALETTE — edit design-tokens.json.\nenum VervfyPalette {\n"
    for key, value in palette.items():
        channels = [int(value[i : i + 2], 16) / 255 for i in (1, 3, 5)]
        swift += f"    static let {key} = Color(.sRGB, red: {channels[0]:.8f}, green: {channels[1]:.8f}, blue: {channels[2]:.8f}, opacity: 1)\n"
    app.write_text(source + swift + "}\n// END GENERATED PALETTE\n")


if __name__ == "__main__":
    generate()
